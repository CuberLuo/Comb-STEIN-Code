## 将命名场景重塑为毒性和疗效剂量组合网格。
## 返回包含 `pT` 和 `pE` 矩阵的列表。
build.pTpE <- function(name) {
  mat <- scenarios[[name]]
  I <- nrow_map[[name]]
  J <- ncol_map[[name]]
  pT <- matrix(mat[, 1], nrow = I, ncol = J, byrow = TRUE)
  pE <- matrix(mat[, 2], nrow = I, ncol = J, byrow = TRUE)
  list(pT = pT, pE = pE)
}
